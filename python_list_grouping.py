numbers = [1, 2, 3, 4, 5, 6, 7]
size = 3

size = int(input("Enter group size: "))
if size < 1:
    print("size must be at least 1")
else:
    start = 0
    while start < len(numbers):
        group = numbers[start:start + size]
        start += size
        print(group)


